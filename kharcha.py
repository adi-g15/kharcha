#!/usr/bin/env python3

import argparse
import sys
from pathlib import Path
import pandas as pd

from backends.hdfc import hdfc_convert_to_ir, hdfc_cc_pdf_convert_to_ir
from backends.sbi import sbi_convert_to_ir
from analyser import kharcha_analysis
from process_ir import assign_types, save_data_in_file, validate_ir

parser = argparse.ArgumentParser(description="Statement Analyzer")

parser.add_argument("--detailed",
                    action='store_true',
                    help="Enable detailed report")
parser.add_argument("--sbi",
                    action="extend", nargs="+", type=str,
                    help="Input is SBI Statement, generated by browser.js (JSON)")
parser.add_argument("--hdfc",
                    action="extend", nargs="+", type=str,
                    help="Input is HDFC/HDFC Credit Card Statement (CSV)")
parser.add_argument("--hdfc-cc",
                    action="extend", nargs="+", type=str,
                    help="Input is HDFC Credit Card Statement (PDF)")
parser.add_argument("--amazon",
                    action="extend", nargs="+", type=str,
                    help="Input is Amazon Pay transactions, generated by browser-amazon-pay.js (JSON)")
parser.add_argument("--json",
                    action="extend", nargs="+", type=str,
                    help="Provide a JSON file for analysis, should be in IR form")
parser.add_argument("--labelled-json",
                   action="extend", nargs="+", type=str,
                   help=("List of already-labelled transactions, to be"
                   " used to categorise data given with other options."))
parser.add_argument("--use-ai",
                    action="store_true",
                    help="Use AI to label the data (default: off)")

args = parser.parse_args()

# Amazon statements are being generated using browser scripts, which
# already generates in the IR format, hence treat the input as if passed to
# '--json'
if args.amazon:
    if args.json is None:
        args.json = []

    args.json.extend(args.amazon)
    args.amazon = None

if not (args.sbi or args.hdfc or args.hdfc_cc or args.json):
    print("One of '--sbi'/'--hdfc'/'--hdfc-cc'/'--amazon'/'--json' is required", file=sys.stderr)
    sys.exit(1)

use_ai = args.use_ai

# STAGE 1 - Convert to JSON (our IR) */
# 
# Every backend should give us data in our IR
# (Intermediate Representation), which is an array of
# JSON objects with these keys at minimum:
# 
# {
#    date: String,
#    text: String,
#    debit: Number,
#    credit: Number,
#  ... any other keys/data, like 'balance'/'note' is also okay but not required
#    }
#

global_df = pd.DataFrame(columns=['date', 'text', 'debit', 'credit'])
type_hints_df = pd.DataFrame(columns=['date', 'text', 'debit', 'credit',
                                      'type', 'will_be_back'])

if args.json:
    for filepath in args.json:
        output = pd.read_json(path_or_buf=filepath, convert_dates=False)
        global_df = pd.concat([global_df, output], axis=0, ignore_index=True)
        validate_ir(global_df)

if args.sbi:
    for filepath in args.sbi:
        output = sbi_convert_to_ir(filepath)
        global_df = pd.concat([global_df, output], axis=0, ignore_index=True)
        validate_ir(global_df)

if args.hdfc:
    for filepath in args.hdfc:
        output = hdfc_convert_to_ir(filepath)
        global_df = pd.concat([global_df, output], axis=0, ignore_index=True)
        validate_ir(global_df)

if args.hdfc_cc:
    for filepath in args.hdfc_cc:
        output = hdfc_cc_pdf_convert_to_ir(filepath)
        global_df = pd.concat([global_df, output], axis=0, ignore_index=True)
        validate_ir(global_df)

if args.labelled_json:
    for filepath in args.labelled_json:
        output = pd.read_json(path_or_buf=filepath, convert_dates=False)

        # 'type' field is required, else we just skip the dataframe
        if "type" not in output.columns:
            continue

        # Only use indices where 'type' or 'will_be_back' is assigned
        indices = (output["type"] != '') | (output["will_be_back"] != 0)
        output = output.loc[indices]

        # Drop columns that we don't expect in IR
        # TODO: mention 'will_be_back' in IR
        output = output[["date","text","debit","credit","type","will_be_back"]]

        # Drop duplicates
        output = output.drop_duplicates()

        type_hints_df = pd.concat([type_hints_df, output], axis=0,
                                  ignore_index=False)

# Drop some invalid columns
if None in global_df.columns:
    global_df = global_df.drop(columns=[None])

if "" in global_df.columns:
    global_df = global_df.drop("", axis=1)

# Clean transaction texts, some transactions, like EMI on hdfc cards has an
# UTF-8 replace character: �
# Remove it, so that transaction names can be matched to type correctly
global_df["text"] = global_df["text"].map(lambda s: s.replace('�',''))

# Clean dataframes, strip all strings
global_df = global_df.map(lambda x: x.strip() if isinstance(x, str) else x)
type_hints_df = type_hints_df.map(lambda x: x.strip() if isinstance(x, str) else x)

stage1_output = global_df

# STAGE 2 - Assign Types
stage2_input = stage1_output
stage2_output = assign_types(stage2_input, use_ai, hints=type_hints_df)

if stage2_output is None:
    print("Stage 1 can't give an output: Backend did not give valid IR")
    sys.exit(1)

save_data_in_file(stage2_output)

# Stage 3 - Analysis
kharcha_analysis(stage2_output, args.detailed)

